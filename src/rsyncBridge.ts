import * as fs from 'fs'
import * as net from 'net'
import * as os from 'os'
import * as path from 'path'
import { randomBytes } from 'crypto'
import { Observable, Subscription } from 'rxjs'

/**
 * Lets a local `rsync` run over an SSH connection Tabby already holds.
 *
 * rsync never speaks SSH itself: it starts a "remote shell" program (`-e`),
 * passing it a host and the remote command (`rsync --server …`), and talks
 * to the remote rsync through that program's stdin/stdout. The bridge gives
 * it such a program — a small helper script — which carries the bytes to
 * this process, where they go out on an exec channel of the Tabby session.
 * Whatever the session needed to authenticate (password, 2FA, jump host,
 * agent) has already happened; rsync never sees any of it.
 *
 * The helper is whatever interpreter the OS ships, since Tabby's binary
 * refuses to run as Node (`ELECTRON_RUN_AS_NODE` has no effect on the
 * installed app) and no Node can be assumed on the machine:
 *
 * - macOS / Linux: Perl (`/usr/bin/perl`), over a Unix socket in a private
 *   0700 directory;
 * - Windows: Windows PowerShell 5.1, present on every install since Windows
 *   10, over a named pipe. Untested at the time of writing — this is the
 *   prototype's Windows leg.
 *
 * Wire format, both directions in frames of `type:u8 length:u32be payload`,
 * after one header line helper → plugin: `<token>\t<remote command>\n`.
 * Helper → plugin: 1 stdin data, 2 stdin EOF (named pipes have no
 * half-close, so EOF has to be a message). Plugin → helper: 1 stdout,
 * 2 stderr, 3 a fatal bridge error (printed to stderr, the helper then
 * exits 255 like ssh would).
 */

/** The host name rsync is given; the helper finds the remote command right after it. */
export const RSYNC_BRIDGE_HOST = 'tabby-bridge'

const FRAME_STDIN = 1
const FRAME_STDIN_EOF = 2
const FRAME_STDOUT = 1
const FRAME_STDERR = 2
const FRAME_FATAL = 3

/** Longest header line accepted before the connection is dropped as garbage. */
const MAX_HEADER_BYTES = 64 * 1024

/** What the bridge needs from an exec channel — russh's `Channel`, minus everything else. */
export interface RsyncExecChannel {
    data$: Observable<Uint8Array>
    extendedData$: Observable<[number, Uint8Array]>
    closed$: Observable<void>
    write (data: Uint8Array): Promise<void>
    eof (): Promise<void>
    close (): Promise<void>
}

/** Opens an exec channel running `command` on the remote side. */
export type RsyncExecOpener = (command: string) => Promise<RsyncExecChannel>

/** Which helper and transport to use — the OS's, unless a test asks otherwise. */
export type RsyncBridgeFlavor = 'perl'|'powershell'

function frame (type: number, payload: Uint8Array): Buffer {
    const out = Buffer.allocUnsafe(5 + payload.length)
    out.writeUInt8(type, 0)
    out.writeUInt32BE(payload.length, 1)
    out.set(payload, 5)
    return out
}

function perlHelper (socketPath: string, token: string): string {
    // Both values are generated here and contain neither quotes nor
    // backslashes (hex token, mkdtemp path checked by the caller), so a
    // single-quoted Perl literal holds them as they are.
    return `#!/usr/bin/perl
# Generated by tabby-better-sidebar: rsync's remote shell (-e), bridged to
# an SSH session of the running Tabby. Deleted when its rsync tab closes.
use strict;
use warnings;
use IO::Socket::UNIX;
use IO::Select;

my $socket_path = '${socketPath}';
my $token = '${token}';
my $host = '${RSYNC_BRIDGE_HOST}';

my $i = 0;
$i++ while $i < @ARGV && $ARGV[$i] ne $host;
die "tabby rsync bridge: host '$host' missing from the arguments\\n" if $i >= @ARGV;
# Joined with spaces, exactly as ssh joins its command arguments.
my $command = join(' ', @ARGV[$i + 1 .. $#ARGV]);
die "tabby rsync bridge: no remote command\\n" if $command eq '';
die "tabby rsync bridge: newline in the remote command\\n" if $command =~ /\\n/;

my $sock = IO::Socket::UNIX->new(Type => SOCK_STREAM(), Peer => $socket_path)
    or die "tabby rsync bridge: Tabby is not reachable ($!) - is the rsync tab still open?\\n";
binmode STDIN; binmode STDOUT; binmode STDERR; binmode $sock;

# rsync puts its ends of the pipes in non-blocking mode, and that flag is
# shared with ours: EAGAIN is routine here, not an error.
sub retryable { return $!{EAGAIN} || $!{EWOULDBLOCK} || $!{EINTR} }

sub write_all {
    my ($fh, $data) = @_;
    my $writable = IO::Select->new($fh);
    while (length $data) {
        my $n = syswrite($fh, $data);
        if (!defined $n) {
            die "tabby rsync bridge: write failed: $!\\n" unless retryable();
            $writable->can_write;
            next;
        }
        substr($data, 0, $n) = '';
    }
}

write_all($sock, "$token\\t$command\\n");

my $select = IO::Select->new(\\*STDIN, $sock);
my $pending = '';
my $exit = 0;
while (1) {
    for my $fh ($select->can_read) {
        my $n = sysread($fh, my $chunk, 65536);
        if (!defined $n) {
            next if retryable();
            die "tabby rsync bridge: read failed: $!\\n";
        }
        if (fileno($fh) == fileno($sock)) {
            exit $exit unless $n;
            $pending .= $chunk;
            while (length($pending) >= 5) {
                my ($type, $len) = unpack('CN', $pending);
                last if length($pending) < 5 + $len;
                my $payload = substr($pending, 5, $len);
                substr($pending, 0, 5 + $len) = '';
                if ($type == ${FRAME_STDOUT}) {
                    write_all(\\*STDOUT, $payload);
                } elsif ($type == ${FRAME_STDERR}) {
                    write_all(\\*STDERR, $payload);
                } elsif ($type == ${FRAME_FATAL}) {
                    write_all(\\*STDERR, "tabby rsync bridge: $payload\\n");
                    $exit = 255;
                }
            }
        } elsif (!$n) {
            $select->remove(\\*STDIN);
            write_all($sock, pack('CN', ${FRAME_STDIN_EOF}, 0));
        } else {
            write_all($sock, pack('CN', ${FRAME_STDIN}, length $chunk) . $chunk);
        }
    }
}
`
}

function powershellHelper (pipeName: string, token: string): string {
    // Windows PowerShell 5.1 syntax only — no ternaries, no `??` — since that
    // is the version every Windows has. Both values are hex or fixed text,
    // safe inside single quotes.
    return `# Generated by tabby-better-sidebar: rsync's remote shell (-e), bridged to
# an SSH session of the running Tabby. Deleted when its rsync tab closes.
$ErrorActionPreference = 'Stop'
# Prototype diagnostics: each step lands in helper.log beside this script,
# readable while a run hangs (the folder goes away with the tab).
$logPath = Join-Path $PSScriptRoot 'helper.log'
function Log([string]$text) { try { Add-Content -Path $logPath -Value ((Get-Date -Format 'HH:mm:ss.fff') + ' ' + $text) } catch { } }
Log ('start, args: ' + (($args | ForEach-Object { '[' + $_ + ']' }) -join ' '))
$pipeName = '${pipeName}'
$token = '${token}'
$bridgeHost = '${RSYNC_BRIDGE_HOST}'

function Fail([string]$message) {
    Log ('fail: ' + $message)
    [Console]::Error.WriteLine("tabby rsync bridge: $message")
    exit 255
}
trap { Fail $_.Exception.Message }

$i = [Array]::IndexOf([string[]]$args, $bridgeHost)
if ($i -lt 0 -or $i -ge $args.Count - 1) { Fail "host '$bridgeHost' or the remote command missing from the arguments" }
# Joined with spaces, exactly as ssh joins its command arguments.
$command = ($args[($i + 1)..($args.Count - 1)]) -join ' '
if ($command.Contains([string][char]10)) { Fail 'newline in the remote command' }

$pipe = New-Object System.IO.Pipes.NamedPipeClientStream('.', $pipeName, [System.IO.Pipes.PipeDirection]::InOut, [System.IO.Pipes.PipeOptions]::Asynchronous)
try { $pipe.Connect(5000) } catch { Fail "Tabby is not reachable ($($_.Exception.Message)) - is the rsync tab still open?" }
Log ('connected, command: ' + $command)

function Send([int]$type, [byte[]]$data, [int]$count) {
    $head = New-Object byte[] 5
    $head[0] = [byte]$type
    $head[1] = [byte](($count -shr 24) -band 0xff)
    $head[2] = [byte](($count -shr 16) -band 0xff)
    $head[3] = [byte](($count -shr 8) -band 0xff)
    $head[4] = [byte]($count -band 0xff)
    $pipe.Write($head, 0, 5)
    if ($count -gt 0) { $pipe.Write($data, 0, $count) }
    $pipe.Flush()
}

$header = [System.Text.Encoding]::UTF8.GetBytes($token + [char]9 + $command + [char]10)
$pipe.Write($header, 0, $header.Length)
Log 'header sent'

$stdin = [Console]::OpenStandardInput()
$stdout = [Console]::OpenStandardOutput()
$stderr = [Console]::OpenStandardError()
$inBuf = New-Object byte[] 65536
$pipeBuf = New-Object byte[] 65536
$pending = New-Object System.IO.MemoryStream
$exitCode = 0
$stdinBytes = 0
$pipeBytes = 0
Log ('stdin redirected: ' + [Console]::IsInputRedirected + ', stdout redirected: ' + [Console]::IsOutputRedirected)

$inTask = $stdin.ReadAsync($inBuf, 0, $inBuf.Length)
$pipeTask = $pipe.ReadAsync($pipeBuf, 0, $pipeBuf.Length)
while ($true) {
    if ($inTask) {
        $tasks = [System.Threading.Tasks.Task[]]@($pipeTask, $inTask)
    } else {
        $tasks = [System.Threading.Tasks.Task[]]@($pipeTask)
    }
    [void][System.Threading.Tasks.Task]::WaitAny($tasks)

    if ($inTask -and $inTask.IsCompleted) {
        $n = $inTask.Result
        if ($n -gt 0) {
            if ($stdinBytes -eq 0) { Log ('first stdin bytes: ' + $n) }
            $stdinBytes += $n
            Send ${FRAME_STDIN} $inBuf $n
            $inTask = $stdin.ReadAsync($inBuf, 0, $inBuf.Length)
        } else {
            Log ('stdin EOF after ' + $stdinBytes + ' bytes')
            Send ${FRAME_STDIN_EOF} $null 0
            $inTask = $null
        }
    }

    if ($pipeTask.IsCompleted) {
        $n = $pipeTask.Result
        if ($n -le 0) { Log ('pipe closed after ' + $pipeBytes + ' bytes'); break }
        if ($pipeBytes -eq 0) { Log ('first pipe bytes: ' + $n) }
        $pipeBytes += $n
        [void]$pending.Seek(0, [System.IO.SeekOrigin]::End)
        $pending.Write($pipeBuf, 0, $n)
        $buf = $pending.GetBuffer()
        $len = [int]$pending.Length
        $pos = 0
        while ($len - $pos -ge 5) {
            $type = [int]$buf[$pos]
            $size = ([int]$buf[$pos + 1] -shl 24) -bor ([int]$buf[$pos + 2] -shl 16) -bor ([int]$buf[$pos + 3] -shl 8) -bor [int]$buf[$pos + 4]
            if ($len - $pos - 5 -lt $size) { break }
            if ($type -eq ${FRAME_STDOUT}) {
                $stdout.Write($buf, $pos + 5, $size)
                $stdout.Flush()
            } elseif ($type -eq ${FRAME_STDERR}) {
                $stderr.Write($buf, $pos + 5, $size)
                $stderr.Flush()
            } elseif ($type -eq ${FRAME_FATAL}) {
                [Console]::Error.WriteLine('tabby rsync bridge: ' + [System.Text.Encoding]::UTF8.GetString($buf, $pos + 5, $size))
                $exitCode = 255
            }
            $pos += 5 + $size
        }
        $rest = New-Object byte[] ($len - $pos)
        [Array]::Copy($buf, $pos, $rest, 0, $len - $pos)
        $pending.SetLength(0)
        $pending.Write($rest, 0, $rest.Length)
        $pipeTask = $pipe.ReadAsync($pipeBuf, 0, $pipeBuf.Length)
    }
}
$stdout.Flush()
Log ('exit ' + $exitCode)
exit $exitCode
`
}

/**
 * One bridge: a private directory holding the helper, and the socket or
 * named pipe the helper dials.
 *
 * Meant to live as long as the tab running rsync — every rsync invocation in
 * that tab goes through it, and `dispose()` removes all traces.
 */
export class RsyncBridge {
    private connections = new Set<net.Socket>()
    private disposed = false
    private logPath: string

    private constructor (
        /** The value to give rsync as `-e`: the helper, and its interpreter where it needs one named. */
        readonly rshCommand: string,
        private directory: string,
        private server: net.Server,
        private token: string,
        private openExec: RsyncExecOpener,
    ) {
        this.logPath = path.join(directory, 'bridge.log')
        server.on('connection', socket => this.serve(socket))
        this.log(`listening, -e ${rshCommand}`)
    }

    /** Prototype diagnostics, beside the helper's own log: see powershellHelper(). */
    private log (text: string): void {
        if (!this.disposed) {
            fs.appendFile(this.logPath, `${new Date().toISOString().slice(11, 23)} ${text}\n`, () => null)
        }
    }

    static async start (openExec: RsyncExecOpener, flavor: RsyncBridgeFlavor = process.platform === 'win32' ? 'powershell' : 'perl'): Promise<RsyncBridge> {
        // mkdtemp creates the directory 0700 on Unix: the socket inside is
        // reachable by this user alone, which is the real access control —
        // the token guards the named pipe, whose default ACL lets only its
        // creator write, and a stale helper dialing a reused address.
        const directory = await fs.promises.mkdtemp(path.join(RsyncBridge.tempRoot(flavor), 'tabby-rsync-'))
        const token = randomBytes(16).toString('hex')
        try {
            let address: string
            let helperPath: string
            let rshCommand: string
            if (flavor === 'powershell') {
                const pipeName = `tabby-rsync-${randomBytes(8).toString('hex')}`
                address = process.platform === 'win32'
                    ? `\\\\.\\pipe\\${pipeName}`
                    // .NET on Unix maps a pipe name to this socket — only
                    // ever reached when a test runs the Windows helper here.
                    : path.join(os.tmpdir(), `CoreFxPipe_${pipeName}`)
                helperPath = path.join(directory, 'rsh.ps1')
                await fs.promises.writeFile(helperPath, powershellHelper(pipeName, token), { mode: 0o600 })
                rshCommand = `${RsyncBridge.powershellPath()} -NoLogo -NoProfile -NonInteractive -ExecutionPolicy Bypass -File "${forwardSlashes(helperPath)}"`
            } else {
                address = path.join(directory, 'bridge.sock')
                helperPath = path.join(directory, 'rsh')
                await fs.promises.writeFile(helperPath, perlHelper(address, token), { mode: 0o700 })
                rshCommand = helperPath
            }
            const server = net.createServer()
            await new Promise<void>((resolve, reject) => {
                server.once('error', reject)
                server.listen(address, () => {
                    server.off('error', reject)
                    resolve()
                })
            })
            return new RsyncBridge(rshCommand, directory, server, token, openExec)
        } catch (e) {
            await fs.promises.rm(directory, { recursive: true, force: true }).catch(() => null)
            throw e
        }
    }

    /**
     * Where the private directory goes.
     *
     * For the Perl helper, two constraints from rsync and the OS rather than
     * taste: its path becomes `-e` as is, which rsync splits on whitespace,
     * and a Unix socket path is capped around 104 bytes on macOS.
     * `os.tmpdir()` satisfies both on stock systems; `/tmp` is the fallback
     * when an override breaks them. The PowerShell helper's path is quoted
     * in `-e` instead, so a Windows profile name with spaces is fine.
     */
    private static tempRoot (flavor: RsyncBridgeFlavor): string {
        const root = os.tmpdir()
        if (flavor === 'powershell') {
            return root
        }
        const usable = !/[\s'"\\]/.test(root) && root.length < 60
        return usable ? root : '/tmp'
    }

    /**
     * Windows PowerShell by absolute path, forward slashes: rsync on Windows
     * is a Cygwin or MSYS2 program, whose `-e` parsing would eat backslashes,
     * and which accepts `C:/…` paths as they are.
     */
    private static powershellPath (): string {
        if (process.platform !== 'win32') {
            return 'pwsh'
        }
        const root = process.env.SystemRoot ?? 'C:\\Windows'
        return forwardSlashes(path.join(root, 'System32', 'WindowsPowerShell', 'v1.0', 'powershell.exe'))
    }

    dispose (): void {
        if (this.disposed) {
            return
        }
        this.disposed = true
        for (const socket of this.connections) {
            socket.destroy()
        }
        this.server.close()
        void fs.promises.rm(this.directory, { recursive: true, force: true }).catch(() => null)
    }

    private serve (socket: net.Socket): void {
        this.log('helper connected')
        this.connections.add(socket)
        socket.on('close', () => this.connections.delete(socket))
        socket.on('error', () => socket.destroy())

        let header = Buffer.alloc(0)
        const onHeader = (chunk: Buffer): void => {
            header = Buffer.concat([header, chunk])
            const newline = header.indexOf(0x0a)
            if (newline < 0) {
                if (header.length > MAX_HEADER_BYTES) {
                    socket.destroy()
                }
                return
            }
            socket.off('data', onHeader)
            // Held until the channel exists: rsync starts writing at once.
            socket.pause()
            const [token, command] = header.subarray(0, newline).toString('utf8').split('\t', 2)
            if (token !== this.token || !command) {
                this.log('bad header, dropped')
                socket.destroy()
                return
            }
            void this.relay(socket, command, header.subarray(newline + 1))
        }
        socket.on('data', onHeader)
    }

    private async relay (socket: net.Socket, command: string, early: Buffer): Promise<void> {
        let channel: RsyncExecChannel
        this.log(`exec: ${command}`)
        try {
            channel = await this.openExec(command)
            this.log('exec channel open')
        } catch (e) {
            this.log(`exec failed: ${(e as Error)?.message ?? e}`)
            socket.end(frame(FRAME_FATAL, Buffer.from(`could not run "${command}" on the server: ${(e as Error)?.message ?? e}`)))
            return
        }
        if (socket.destroyed) {
            void channel.close().catch(() => null)
            return
        }

        let fromServer = 0
        let toServer = 0
        const subscriptions: Subscription[] = []
        // No backpressure towards the server here: russh's channel cannot be
        // paused from JS, so a slow local rsync makes this side buffer. The
        // other direction — the one uploads load — is throttled below.
        subscriptions.push(channel.data$.subscribe(data => {
            if (!fromServer) {
                this.log(`first bytes from the server: ${data.length}`)
            }
            fromServer += data.length
            socket.write(frame(FRAME_STDOUT, data))
        }))
        subscriptions.push(channel.extendedData$.subscribe(([, data]) => {
            this.log(`server stderr: ${Buffer.from(data).toString('utf8').trim()}`)
            socket.write(frame(FRAME_STDERR, data))
        }))
        subscriptions.push(channel.closed$.subscribe(() => {
            this.log(`channel closed, ${fromServer} bytes from / ${toServer} bytes to the server`)
            subscriptions.forEach(s => s.unsubscribe())
            socket.end()
        }))
        socket.on('close', () => {
            this.log('helper disconnected')
            subscriptions.forEach(s => s.unsubscribe())
            void channel.close().catch(() => null)
        })

        // Writes are chained so they reach the channel in order, and the
        // socket stays paused while any is in flight: that pause is what
        // keeps a fast local disk from piling an upload up in memory.
        let writes = Promise.resolve()
        let inFlight = 0
        let pending = early
        const consume = (): void => {
            while (pending.length >= 5) {
                const type = pending.readUInt8(0)
                const length = pending.readUInt32BE(1)
                if (pending.length < 5 + length) {
                    break
                }
                const payload = pending.subarray(5, 5 + length)
                pending = pending.subarray(5 + length)
                if (type === FRAME_STDIN) {
                    if (!toServer) {
                        this.log(`first bytes to the server: ${payload.length}`)
                    }
                    toServer += payload.length
                    inFlight++
                    socket.pause()
                    writes = writes
                        .then(() => channel.write(payload))
                        .then(() => {
                            if (--inFlight === 0) {
                                socket.resume()
                            }
                        })
                        .catch(() => { socket.destroy() })
                } else if (type === FRAME_STDIN_EOF) {
                    this.log('stdin EOF from the helper')
                    writes = writes.then(() => channel.eof()).catch(() => null)
                }
            }
        }
        socket.on('data', (chunk: Buffer) => {
            pending = pending.length ? Buffer.concat([pending, chunk]) : chunk
            consume()
        })
        consume()
        if (!inFlight) {
            socket.resume()
        }
    }
}

function forwardSlashes (p: string): string {
    return p.replace(/\\/g, '/')
}
